import { executeTool, type ToolContext, type ToolOutput } from '../tools/toolbox.js';
import type { ToolTraceEntry } from '../tools/trace.js';
import { summarizeArgs } from '../tools/trace.js';

/**
 * Learning path (5.5): the shortest dependency walk between two components, as an ordered list of
 * hops, each annotated with the decision(s) in force and the owner of record of that component.
 *
 * Everything comes from the graph: the walk is `path_between` (algo.SPpaths), the annotations come
 * from `counterfactual_impact`, which already returns decisions and owners per component. There
 * is no new query and nothing is generated by a model.
 *
 * Direction: the walk follows DEPENDS_ON, so every hop is something the previous one depends on.
 * Read it as "start here, then learn this, because it depends on it".
 */

export interface LearningPathDecision {
  id: string;
  title?: string | null;
  status?: string | null;
}

export interface LearningPathOwner {
  id: string;
  name?: string | null;
  pattern?: string | null;
}

export interface LearningPathHop {
  /** 0 = where you start. */
  index: number;
  component: string;
  role: 'start' | 'step' | 'goal';
  /** PageRank of the component (how central it is); null when unknown. */
  pageRank: number | null;
  /** Decisions in force that govern the component. */
  decisions: LearningPathDecision[];
  /** CODEOWNERS owners of record. */
  owners: LearningPathOwner[];
  /** False when the annotation lookup failed or was out of range: the hop is shown without them. */
  annotated: boolean;
}

export interface LearningPath {
  source: string;
  target: string;
  /** False when the graph has no dependency path between the two components. */
  found: boolean;
  /** Number of DEPENDS_ON edges on the walk. */
  length: number;
  hops: LearningPathHop[];
}

/** Longest walk we annotate (counterfactual_impact allows depth 1..5). */
export const LEARNING_PATH_MAX_ANNOTATED_HOPS = 5;
export const LEARNING_PATH_MAX_PATHS = 3;

interface ImpactRow {
  target?: string;
  component?: string;
  direction?: string;
  hops?: number;
  score?: number | null;
  decisions?: Array<{ id?: string; title?: string | null; status?: string | null } | null>;
  owners?: Array<{ id?: string; name?: string | null; pattern?: string | null } | null>;
}

export interface ComponentAnnotation {
  pageRank: number | null;
  decisions: LearningPathDecision[];
  owners: LearningPathOwner[];
}

/**
 * Reads the component names out of a compacted `path_between` row. The query returns
 * `{path, pathWeight}` and compaction turns the path into `{_path: [names], length, relationships}`;
 * a bare `{_path}` is accepted too.
 */
export function pathComponents(row: unknown): string[] {
  const r = row as { _path?: unknown; path?: { _path?: unknown } } | null | undefined;
  const p = r?.path?._path ?? r?._path;
  return Array.isArray(p) ? p.filter((x): x is string => typeof x === 'string' && x.length > 0) : [];
}

/** Folds `counterfactual_impact` rows into per-component annotations. */
export function annotationsFromImpact(rows: unknown[]): Map<string, ComponentAnnotation> {
  const out = new Map<string, ComponentAnnotation>();
  for (const r of rows as ImpactRow[]) {
    if (!r || typeof r.component !== 'string' || out.has(r.component)) continue;
    out.set(r.component, {
      pageRank: typeof r.score === 'number' && Number.isFinite(r.score) ? r.score : null,
      decisions: (r.decisions ?? [])
        .filter((d): d is NonNullable<typeof d> => Boolean(d && typeof d.id === 'string' && d.id))
        .map((d) => ({ id: d.id!, title: d.title ?? null, status: d.status ?? null })),
      owners: (r.owners ?? [])
        .filter((o): o is NonNullable<typeof o> => Boolean(o && typeof o.id === 'string' && o.id))
        .map((o) => ({ id: o.id!, name: o.name ?? null, pattern: o.pattern ?? null })),
    });
  }
  return out;
}

/**
 * Builds the learning path for one `path_between` result. Pure: pass `components` (the walk, empty
 * when the graph has no path) and the annotations looked up for them.
 */
export function buildLearningPath(
  source: string,
  target: string,
  components: string[],
  annotations: Map<string, ComponentAnnotation>
): LearningPath {
  if (components.length === 0) {
    return { source, target, found: false, length: 0, hops: [] };
  }
  const last = components.length - 1;
  const hops: LearningPathHop[] = components.map((component, index) => {
    const a = annotations.get(component);
    return {
      index,
      component,
      role: index === 0 ? 'start' : index === last ? 'goal' : 'step',
      pageRank: a?.pageRank ?? null,
      decisions: a?.decisions ?? [],
      owners: a?.owners ?? [],
      annotated: Boolean(a),
    };
  });
  // a single-node walk (source === target) is a walk of length 0 whose only hop is the start
  if (hops.length === 1) hops[0]!.role = 'start';
  return { source, target, found: true, length: last, hops };
}

export interface AssembleLearningPathsOptions {
  ctx: ToolContext;
  workspaceId: string;
  /** `path_between` calls the LLM planner made and their results. */
  pathCalls: Array<{ entry: ToolTraceEntry; output: ToolOutput }>;
  asOf: number;
}

/**
 * Turns the planner's `path_between` results into learning paths. The annotation lookups are
 * ordinary toolbox calls, so they are returned as trace entries (the answer stays explainable).
 * Best effort: a failed lookup leaves the hops unannotated instead of dropping the path.
 */
export async function assembleLearningPaths(
  opts: AssembleLearningPathsOptions
): Promise<{ paths: LearningPath[]; trace: ToolTraceEntry[] }> {
  const paths: LearningPath[] = [];
  const trace: ToolTraceEntry[] = [];
  const seen = new Set<string>();

  for (const { entry, output } of opts.pathCalls) {
    if (entry.tool !== 'path_between' || !output.ok) continue;
    const source = String(entry.args.sourceName ?? '');
    const target = String(entry.args.targetName ?? '');
    if (!source || !target) continue;
    const key = `${source}\u0000${target}`;
    if (seen.has(key)) continue;
    seen.add(key);
    if (paths.length >= LEARNING_PATH_MAX_PATHS) break;

    const components = pathComponents(output.rows[0]);
    if (components.length === 0) {
      paths.push(buildLearningPath(source, target, [], new Map()));
      continue;
    }

    // Everything on the walk is a dependency of `source` and a dependent of `target`, so two calls
    // annotate the whole walk (each leaves out only the component it was asked about).
    const depth = Math.min(Math.max(components.length - 1, 1), LEARNING_PATH_MAX_ANNOTATED_HOPS);
    const annotations = new Map<string, ComponentAnnotation>();
    for (const anchor of [components[0]!, components[components.length - 1]!]) {
      if (components.length === 1) break;
      const args = { component: anchor, asOf: opts.asOf, maxDepth: depth, limit: 100 };
      const started = Date.now();
      const out = await executeTool(opts.ctx, opts.workspaceId, 'counterfactual_impact', args);
      trace.push({
        step: 0,
        source: 'pipeline',
        tool: 'counterfactual_impact',
        args: summarizeArgs(args),
        status: out.ok ? 'ok' : 'error',
        rowCount: out.rowCount,
        evidenceIds: out.evidence.primaryIds.length,
        durationMs: Date.now() - started,
        note: out.ok ? 'annotates the learning path' : out.error,
      });
      if (!out.ok) continue;
      for (const [name, a] of annotationsFromImpact(out.rows)) {
        if (components.includes(name) && !annotations.has(name)) annotations.set(name, a);
      }
    }
    paths.push(buildLearningPath(source, target, components, annotations));
  }
  return { paths, trace };
}
